// scripts/lib/api-linked-pages.mjs: the docs pages mnemom-api links to (MNE-10095).
//
// The Org Scan report mnemom-api builds and signs links customers to docs pages
// from its fix table and its published target. mnemom-api checks those links
// against its own vendored copy of the docs navigation
// (src/org-scan/row-builder/__fixtures__/docs-pages.v1.json), which is pinned to
// one docs commit. That test cannot see a later docs change, so docs holds the
// other half: scripts/api-linked-pages.json lists every page the api links, and
// scripts/check-api-linked-pages.mjs fails a docs PR that removes or renames one
// without a redirect.
//
// Refresh paths, one for each list:
//   docs list  node scripts/sync-api-linked-pages.mjs
//              Reads the files in SOURCES from mnemom-api and keeps every
//              https://docs.mnemom.ai/<page> link in them. The scheduled
//              "Code facts" workflow runs it with --check and goes red when
//              the api links a page this list does not hold.
//   api list   In mnemom-api, rebuild docs-pages.v1.json from docs.json at the
//              new mnemom/docs commit. The steps are in that file's
//              "description". Do this after a docs change that moves a listed
//              page, then point the api link at the new page.

import { existsSync } from "node:fs";
import { join } from "node:path";

export const API_LINKED_PAGES_SCHEMA = "mnemom-api-linked-pages/1";
export const DOCS_ORIGIN = "https://docs.mnemom.ai";
export const API_REPO = "mnemom/mnemom-api";

/** The mnemom-api files whose docs links reach a customer in an Org Scan report. */
export const SOURCES = [
  "src/org-scan/claim-lint/claim-lint.ts",
  "src/org-scan/row-builder/fix-table.ts",
  "src/org-scan/row-builder/targets.ts",
];

export class ApiLinkedPagesError extends Error {}

const NOTE =
  "Docs pages that mnemom-api links to from the Org Scan report, generated by scripts/sync-api-linked-pages.mjs from the mnemom-api files in `sources`. Do not hand-edit: re-run the sync script. scripts/check-api-linked-pages.mjs fails docs CI when a page here has no page file and no redirect, and the scheduled 'Code facts' workflow checks this file against mnemom-api main. mnemom-api keeps its own list of docs pages in src/org-scan/row-builder/__fixtures__/docs-pages.v1.json. After a listed page moves, refresh that file from docs.json as its description says and point the api link at the new page.";

// The page part matches the api's own DOCS_URL_RE (src/org-scan/report-schema-v2.ts).
const LINK_RE = /https:\/\/docs\.mnemom\.ai\/([A-Za-z0-9._~/-]+)/g;

/** `/foo/bar/#x?y` → `foo/bar`. */
export const toSlug = (path) => path.split(/[#?]/)[0].replace(/^\/+|\/+$/g, "");

/** Page slugs of every docs.mnemom.ai link in a source text, sorted and unique. */
export function extractSlugs(text) {
  const out = new Set();
  for (const m of text.matchAll(LINK_RE)) {
    // A link at the end of a sentence or a template string picks up its punctuation.
    const slug = toSlug(m[1].replace(/[.~-]+$/, ""));
    if (slug) out.add(slug);
  }
  return [...out].sort();
}

/** inputs: [{ path, text }] for each file in SOURCES. */
export function buildList(inputs, ref) {
  const pages = {};
  for (const { path, text } of [...inputs].sort((a, b) => (a.path < b.path ? -1 : 1))) {
    for (const slug of extractSlugs(text)) (pages[slug] ??= { linked_from: [] }).linked_from.push(path);
  }
  if (!Object.keys(pages).length) throw new ApiLinkedPagesError("no docs.mnemom.ai link found in any source file");
  return {
    _note: NOTE,
    schema: API_LINKED_PAGES_SCHEMA,
    origin: DOCS_ORIGIN,
    repo: API_REPO,
    ref,
    sources: inputs.map((i) => i.path).sort(),
    pages: Object.fromEntries(Object.entries(pages).sort(([a], [b]) => (a < b ? -1 : 1))),
  };
}

export const serializeList = (list) => `${JSON.stringify(list, null, 2)}\n`;

export function validateList(list) {
  const bad = (m) => {
    throw new ApiLinkedPagesError(`api-linked-pages.json: ${m}`);
  };
  if (!list || typeof list !== "object") bad("not an object");
  if (list.schema !== API_LINKED_PAGES_SCHEMA) bad(`schema must be ${API_LINKED_PAGES_SCHEMA}`);
  if (list.origin !== DOCS_ORIGIN) bad(`origin must be ${DOCS_ORIGIN}`);
  if (typeof list.ref !== "string" || !list.ref) bad("ref must say which mnemom-api ref the list came from");
  if (!list.pages || typeof list.pages !== "object" || !Object.keys(list.pages).length) bad("pages must list at least one page");
  for (const [slug, page] of Object.entries(list.pages)) {
    if (slug !== toSlug(slug) || !slug) bad(`"${slug}" is not a page slug`);
    if (!Array.isArray(page?.linked_from) || !page.linked_from.length) bad(`"${slug}" must name the api file that links it`);
  }
}

/** What changed between the committed list and one just built from the api. */
export function diffLists(committed, live) {
  const out = [];
  for (const slug of Object.keys(live.pages)) {
    if (!committed.pages[slug]) out.push(`mnemom-api now links /${slug} (${live.pages[slug].linked_from.join(", ")}), which the list does not hold`);
  }
  for (const slug of Object.keys(committed.pages)) {
    if (!live.pages[slug]) out.push(`mnemom-api no longer links /${slug}, which the list still holds`);
    else if (JSON.stringify(committed.pages[slug].linked_from) !== JSON.stringify(live.pages[slug].linked_from)) {
      out.push(`/${slug} is now linked from ${live.pages[slug].linked_from.join(", ")}`);
    }
  }
  return out;
}

const hasPageFile = (root, slug) =>
  [`${slug}.mdx`, `${slug}.md`, `${slug}/index.mdx`, `${slug}/index.md`].some((rel) => existsSync(join(root, rel)));

/**
 * One problem line for each listed page a customer's link would not reach.
 * A page resolves when it has a page file, or when docs.json redirects its exact
 * path, in one or more hops, to a path that has one. A wildcard redirect does
 * not count: write the exact path so the intent is on record.
 */
export function checkPages(list, docs, root) {
  const redirects = new Map();
  for (const r of docs.redirects ?? []) {
    if (typeof r?.source !== "string" || typeof r?.destination !== "string") continue;
    if (/[:*]/.test(r.source) || /[:*]/.test(r.destination.replace(/^https?:/, ""))) continue;
    if (!redirects.has(toSlug(r.source))) redirects.set(toSlug(r.source), r.destination);
  }
  const problems = [];
  for (const [slug, page] of Object.entries(list.pages)) {
    if (hasPageFile(root, slug)) continue;
    const from = `mnemom-api links ${list.origin}/${slug} from ${page.linked_from.join(", ")}`;
    const seen = new Set([slug]);
    let at = slug;
    let why = "";
    while (!why) {
      const dest = redirects.get(at);
      if (dest === undefined) {
        why = at === slug ? "it has no page file and no redirect" : `its redirect ends at /${at}, which has no page file`;
      } else if (/^https?:\/\//.test(dest)) {
        why = `its redirect leaves the docs site (${dest})`;
      } else {
        at = toSlug(dest);
        if (hasPageFile(root, at)) break;
        if (seen.has(at)) why = "its redirect loops";
        seen.add(at);
      }
    }
    if (why) {
      problems.push(
        `/${slug}: ${why}. ${from}, and a signed report already sent keeps that link. ` +
          `Restore the page, or add a redirect from /${slug} to its new page in docs.json.`,
      );
    }
  }
  return problems;
}
