#!/usr/bin/env node
/**
 * Generate `api-reference/webhook-events.mdx` from the canonical
 * webhook event catalog at `mnemom-api/schemas/webhooks/index.json`.
 *
 * The schemas are the source of truth. Re-run this script whenever
 * the catalog evolves (new event added, schema description updated):
 *
 *   node scripts/generate-webhook-catalog.mjs
 *
 * The script expects `mnemom-api` checked out as a sibling repo at
 * `../mnemom-api/`. Override with the MNEMOM_API_PATH env var:
 *
 *   MNEMOM_API_PATH=../foo/mnemom-api node scripts/generate-webhook-catalog.mjs
 *
 * Per ADR-050: catalog source-of-truth lives next to the emitter
 * (mnemom-api). This script copies into the docs build at write
 * time; CI also runs it as a coherence check (drift fails CI).
 */

import { readFileSync, writeFileSync, existsSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const DOCS_ROOT = dirname(__dirname);
const API_PATH = process.env.MNEMOM_API_PATH ?? join(DOCS_ROOT, '..', 'mnemom-api');
const SCHEMAS_DIR = join(API_PATH, 'schemas', 'webhooks');
const OUTPUT_PATH = join(DOCS_ROOT, 'api-reference', 'webhook-events.mdx');

const GITHUB_BASE = 'https://github.com/mnemom/mnemom-api/blob/main/schemas/webhooks';

const FAMILY_BLURBS = {
  'agent': 'Lifecycle and exemption events for individual agents.',
  'billing': 'Stripe-driven billing state and AAP transaction outcomes.',
  'conscience': 'Conscience escalations from AIP analysis and org-level values updates.',
  'governance': 'Card and template updates that flow through the composer to affect future agent turns.',
  'integrity': 'AIP integrity-checkpoint events fired after every analyze pass.',
  'quota': 'Org-level quota and risk-budget threshold crossings.',
  'reputation': 'Per-agent reputation evolution. (Catalog-only as of 2026-05-09 — emitter wiring pending.)',
  'safe-house': 'Front-door evaluation outcomes and security tripwires. `sh.evaluation.*` fires per screened surface, not per request — the front door screens the inbound message when the request arrives and each tool result turn-internally, inline, before that request is forwarded, so one request can emit several of these events. See [When the front door runs](/concepts/safe-house#when-the-front-door-runs). (Catalog-only as of 2026-05-09 — emitter wiring pending.)',
  'sideband': 'Cross-turn detector firings (drift, coherence, fault-line, fleet) and operator-marked drift resolutions.',
  'team': 'Team lifecycle and membership events.',
  'trace': 'AAP alignment-trace verification and policy-violation events. (Emitted via the parallel AAP webhook rail — see debt #18.)',
};

function familyTitle(fam) {
  return fam.split('-').map(s => s[0].toUpperCase() + s.slice(1)).join(' ');
}

function loadCatalog() {
  if (!existsSync(SCHEMAS_DIR)) {
    throw new Error(
      `Schemas directory not found: ${SCHEMAS_DIR}\n` +
      `Set MNEMOM_API_PATH or check out mnemom-api as a sibling.`,
    );
  }
  const indexPath = join(SCHEMAS_DIR, 'index.json');
  const index = JSON.parse(readFileSync(indexPath, 'utf-8'));
  const events = [];
  for (const [name, meta] of Object.entries(index.events)) {
    const schema = JSON.parse(readFileSync(join(SCHEMAS_DIR, meta.schema), 'utf-8'));
    events.push({
      family: meta.family ?? '?',
      name,
      description: schema.description ?? schema.title ?? '',
      schemaPath: meta.schema,
      examplePath: meta.example,
    });
  }
  return { catalogVersion: index.catalog_version, events };
}

function generateMdx({ catalogVersion, events }) {
  const families = {};
  for (const e of events) {
    (families[e.family] ??= []).push(e);
  }
  for (const fam of Object.keys(families)) {
    families[fam].sort((a, b) => a.name.localeCompare(b.name));
  }

  const lines = [];
  lines.push('---');
  lines.push('title: "Webhook Event Catalog"');
  lines.push(`description: "All ${events.length} webhook event types Mnemom emits, with JSON Schema and example payload links. Operator-actionable surface only per ADR-048 §I15."`);
  lines.push('sidebarTitle: "Webhook Events"');
  lines.push('icon: "list"');
  lines.push('---');
  lines.push('');
  lines.push(`The full catalog of webhook events Mnemom emits — **${events.length} events as of ${catalogVersion}**, grouped by family. Every entry has a versioned JSON Schema, an example payload, and an emission-site reference.`);
  lines.push('');
  lines.push('The schemas are the source of truth (canonical home: `mnemom-api/schemas/webhooks/`). This page is generated by `scripts/generate-webhook-catalog.mjs` from `mnemom-api/schemas/webhooks/index.json`; CI ensures the page stays in sync with the catalog.');
  lines.push('');
  lines.push('Every event in this catalog satisfies the [seven contractual invariants](/concepts/webhook-contract) — stable name, versioned JSON Schema, example payload, idempotency key, HMAC signature, retry policy, replay path. All entries are classified `operator-actionable` per [§I15](https://github.com/mnemom/safe-house-hardening/blob/main/audit/i15-conformance-2026-05-09.md).');
  lines.push('');
  lines.push(`**Catalog version:** \`${catalogVersion}\`. Subscription to a new endpoint defaults to \`event_types: []\` (none) — explicit per-event opt-in is required.`);
  lines.push('');
  lines.push('---');
  lines.push('');

  for (const fam of Object.keys(families).sort()) {
    lines.push(`## ${familyTitle(fam)} family`);
    lines.push('');
    if (FAMILY_BLURBS[fam]) {
      lines.push(FAMILY_BLURBS[fam]);
      lines.push('');
    }
    for (const e of families[fam]) {
      lines.push(`### \`${e.name}\``);
      lines.push('');
      if (e.description) {
        lines.push(e.description);
        lines.push('');
      }
      lines.push(`- [Schema](${GITHUB_BASE}/${e.schemaPath})`);
      lines.push(`- [Example payload](${GITHUB_BASE}/${e.examplePath})`);
      lines.push('');
    }
  }

  lines.push('---');
  lines.push('');
  lines.push('## See also');
  lines.push('');
  lines.push('- [Webhook Contract](/concepts/webhook-contract) — the seven contractual invariants.');
  lines.push('- [Headers reference](/api-reference/headers) — `X-Webhook-Signature` + `X-Webhook-Timestamp` + `X-Webhook-Id` delivery headers.');
  lines.push('- [§I15 conformance audit](https://github.com/mnemom/safe-house-hardening/blob/main/audit/i15-conformance-2026-05-09.md) — per-event classification and the surface-separation reasoning.');

  return lines.join('\n') + '\n';
}

const catalog = loadCatalog();
const mdx = generateMdx(catalog);
writeFileSync(OUTPUT_PATH, mdx);
console.log(`✓ Generated ${OUTPUT_PATH} (${catalog.events.length} events, catalog ${catalog.catalogVersion})`);
